package If;

public class If_Exemplo_2{

	public static void main(String[] args) {
		double nota = 6.0;
		
		if (nota >= 7){
			System.out.println("Você está aprovado !");	
			
		} else if (nota >= 5) {
			System.out.println("Você está de recuperação !");
			
		}else {
		
		System.out.println("Você está reprovado !");	
		
		}
			
		
		
		
		
	}

}
